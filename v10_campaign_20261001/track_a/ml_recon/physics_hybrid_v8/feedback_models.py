    def _coordinate_fourier_features(
        x_coordinate: "torch.Tensor",
        y_coordinate: "torch.Tensor",
    ) -> "torch.Tensor":
        values = [x_coordinate, y_coordinate]
        for harmonic in (1.0, 2.0, 4.0, 8.0):
            values.extend((
                torch.sin(math.pi * harmonic * x_coordinate),
                torch.cos(math.pi * harmonic * x_coordinate),
                torch.sin(math.pi * harmonic * y_coordinate),
                torch.cos(math.pi * harmonic * y_coordinate),
            ))
        return torch.stack(values, dim=-1)


    def _gather_recent_history(
        history_token: "torch.Tensor",
        valid: "torch.Tensor",
        *,
        recent_count: int,
    ) -> Tuple["torch.Tensor", "torch.Tensor"]:
        history_count = history_token.shape[1]
        if recent_count > history_count:
            raise ValueError("recent history cannot exceed maximum history")
        positions = torch.arange(history_count, device=history_token.device)[None, :]
        score = torch.where(valid, positions, torch.full_like(positions, -1))
        selected_score, selected_index = torch.topk(
            score,
            recent_count,
            dim=1,
            largest=True,
            sorted=True,
        )
        selected_score = torch.flip(selected_score, dims=(1,))
        selected_index = torch.flip(selected_index, dims=(1,))
        gather_index = selected_index[:, :, None].expand(-1, -1, history_token.shape[-1])
        selected_token = torch.gather(history_token, dim=1, index=gather_index)
        selected_valid = selected_score >= 0
        return selected_token * selected_valid[:, :, None], selected_valid


    def _candidate_action_set(
        action: "torch.Tensor",
        action_mask: "torch.Tensor",
    ) -> "torch.Tensor":
        no_op = torch.zeros_like(action)
        phase_only = action.clone()
        phase_only[:, :3] = 0.0
        amplitude_only = action.clone()
        amplitude_only[:, 3:] = 0.0
        candidates = torch.stack((
            no_op,
            0.25 * phase_only,
            0.50 * phase_only,
            phase_only,
            amplitude_only,
            action,
        ), dim=1)
        phase_size = candidates[:, :, 3:].abs().amax(dim=-1)
        phase_keep = (
            (phase_size == 0.0) | (phase_size >= PHASE_ACTION_MIN_RAD)
        ).to(dtype=candidates.dtype)
        candidates = torch.cat((
            candidates[:, :, :3],
            candidates[:, :, 3:] * phase_keep[:, :, None],
        ), dim=-1)
        return candidates * action_mask[:, None, :]


