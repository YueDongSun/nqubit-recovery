def static_transport_compatibility(
    source_embedding: "torch.Tensor",
    target_embedding: "torch.Tensor",
    *,
    temperature: float = 0.10,
) -> "torch.Tensor":
    """Cosine compatibility for static state-pair weak supervision only.

    The function intentionally accepts no action, Jacobian, or policy value;
    callers therefore cannot accidentally relabel reconstructed state pairs as
    real control-response supervision through this API.
    """

    if torch is None:  # pragma: no cover
        raise RuntimeError("V8 transport compatibility requires torch")
    if source_embedding.shape != target_embedding.shape:
        raise ValueError("transport endpoint embeddings must have equal shapes")
    if source_embedding.ndim != 2:
        raise ValueError("transport endpoint embeddings must be [batch, feature]")
    if float(temperature) <= 0.0:
        raise ValueError("transport temperature must be positive")
    source = functional.normalize(source_embedding, dim=-1, eps=1e-8)
    target = functional.normalize(target_embedding, dim=-1, eps=1e-8)
    return (source * target).sum(dim=-1) / float(temperature)


