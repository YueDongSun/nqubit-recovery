// Clock wrapper: 50 MHz input (inclk0) doubled to 100 MHz on c0.
// The production image instantiates the Altera ALTPLL megafunction here
// (Quartus II 13.0 SP1 megafunction wizard parameters: inclk0 50 MHz,
// c0 multiply 2 / divide 1, duty 50%, NO_COMPENSATION, bandwidth AUTO,
// device family Cyclone III). Regenerate that wrapper with the Quartus
// megafunction wizard (ALTPLL) using the parameters in this header, or
// keep this module and feed the design from an external 100 MHz clock.
//
// This file ships as a simulation/model stub WITHOUT the Altera license
// block: for the FPGA build, replace the body with the wizard-generated
// altpll instantiation (the original wrapper was removed for license
// compliance; its parameters are recorded verbatim above).
module pll (
    inclk0,
    c0);

    input  inclk0;
    output c0;

    // Behavioral model: 2x frequency doubling. Functional for simulation
    // and for the UART/timing logic that only needs a doubled clock; the
    // real hardware PLL is generated by the Quartus ALTPLL wizard.
    reg c0_reg;
    initial c0_reg = 1'b0;
    always
        c0_reg = #5000 ~c0_reg;   // 50 MHz in -> 100 MHz out (10 ns period)

    assign c0 = c0_reg;

endmodule
